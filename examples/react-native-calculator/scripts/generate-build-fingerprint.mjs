export async function computeBuildFingerprint(appRoot = DEFAULT_APP_ROOT) {
  const repoRoot = resolve(appRoot, '../..');
  const files = await buildInputFiles(appRoot);
  const hasher = createHash('sha256');
  for (const path of files) {
    hasher.update(relative(repoRoot, path).replaceAll('\\', '/'));
    hasher.update('\0');
    hasher.update(await readFile(path));
    hasher.update('\0');
  }
  return { fingerprint: hasher.digest('hex'), inputCount: files.length };
}

export function renderBuildFingerprint({ fingerprint, inputCount }) {
  return `// AUTO-GENERATED by bun run build:fingerprint. DO NOT EDIT.\nexport const UNIKIT_BUILD_FINGERPRINT =\n  '${fingerprint}';\nexport const UNIKIT_BUILD_INPUT_COUNT = ${inputCount};\n`;
}

export async function main() {
  const result = await computeBuildFingerprint();
  const path = resolve(DEFAULT_APP_ROOT, BUILD_FINGERPRINT_PATH);
  const rendered = renderBuildFingerprint(result);
  const current = await Bun.file(path)
    .text()
    .catch(() => undefined);
  if (current !== rendered) await Bun.write(path, rendered);
  console.log(`Unikit build fingerprint: ${result.fingerprint} (${result.inputCount} inputs)`);
}

if (import.meta.main) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  });
}
