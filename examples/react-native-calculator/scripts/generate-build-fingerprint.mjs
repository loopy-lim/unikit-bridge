import { createHash } from 'node:crypto';
import { readdir, readFile } from 'node:fs/promises';
import { dirname, extname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
export const DEFAULT_APP_ROOT = resolve(SCRIPT_DIR, '..');
export const BUILD_FINGERPRINT_PATH = 'src/build-fingerprint.ts';

const EXCLUDED_SUFFIXES = ['.test.ts', '.test.tsx', '.test.mjs'];

async function collectFiles(path, extensions, output) {
  const entries = await readdir(path, { withFileTypes: true });
  for (const entry of entries) {
    if (['node_modules', 'target', 'Pods', 'build', '.cxx', 'rust'].includes(entry.name)) continue;
    const entryPath = resolve(path, entry.name);
    if (entry.isDirectory()) {
      await collectFiles(entryPath, extensions, output);
    } else if (
      extensions.has(extname(entry.name)) &&
      !EXCLUDED_SUFFIXES.some((suffix) => entry.name.endsWith(suffix)) &&
      entry.name !== 'build-fingerprint.ts'
    ) {
      output.push(entryPath);
    }
  }
}

